package _05.조건문;

public class Ex01 {
    public static void main(String[] args) {
        int score = 85;

        // 60이상 "합격입니다!", 그렇지 않으면 "불합격입니다!"
        if (score >= 60) {
            System.out.println("합격입니다.");
        } else {
            System.out.println("불합격입니다.");
        }

    }
}
